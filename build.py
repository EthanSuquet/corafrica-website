def roles_of(name):
    out = []
    for group, where in ((BOARD_NG, "Board of Trustees, Nigeria"), (BOARD_US, "Board of Trustees, United States"),
                         (ADMIN, "")):
        for n, r in group:
            label = r if (not where or r == "Founder") else "%s, %s" % (r, where)
            if n == name and label not in out:
                out.append(label)
    return out


