def _gear():
    """The skills-centre glyph, generated rather than hand-drawn: a hub and eight teeth."""
    d = ["M12 8.4a3.6 3.6 0 1 0 0 7.2 3.6 3.6 0 0 0 0-7.2z"]
    for k in range(8):
        a = math.radians(k * 45)
        c, s_ = math.cos(a), math.sin(a)
        d.append("M%.1f %.1fL%.1f %.1f" % (12 + 6.4 * c, 12 + 6.4 * s_,
                                           12 + 9.6 * c, 12 + 9.6 * s_))
    return "".join(d)


